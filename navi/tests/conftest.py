"""保证仓库根目录在 sys.path 上，避免 `import navi` 因 cwd/安装方式不同而失败。"""

import sys
from pathlib import Path

_REPO_ROOT = str(Path(__file__).resolve().parents[2])
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)
